import type { LanguageCode, Lesson } from "@/types/learning";

type SupplementalLessonSeed = {
  coverEmoji: string;
  id: string;
  languageId: LanguageCode;
  order: number;
  samplePhrase: string;
  subtitle: string;
  title: string;
  translation: string;
  unitId: string;
};

function createSupplementalLesson({
  coverEmoji,
  id,
  languageId,
  order,
  samplePhrase,
  subtitle,
  title,
  translation,
  unitId,
}: SupplementalLessonSeed): Lesson {
  const vocabularyId = `${id}-vocabulary`;
  const phraseId = `${id}-phrase`;

  return {
    id,
    languageId,
    unitId,
    title,
    subtitle,
    order,
    level: "beginner",
    xpReward: 20,
    estimatedMinutes: 6,
    coverEmoji,
    goals: [
      {
        id: `${id}-goal-1`,
        title: `Understand ${title.toLowerCase()}`,
        description: `Recognize a useful phrase for ${title.toLowerCase()}.`,
      },
      {
        id: `${id}-goal-2`,
        title: "Speak with confidence",
        description: "Repeat the key phrase in a short conversation.",
      },
    ],
    vocabulary: [
      {
        id: vocabularyId,
        term: samplePhrase,
        translation,
        partOfSpeech: "phrase",
      },
    ],
    phrases: [
      {
        id: phraseId,
        text: samplePhrase,
        translation,
      },
    ],
    activities: [
      {
        id: `${id}-activity-1`,
        type: "vocabulary-card",
        skill: "vocabulary",
        prompt: `Learn: ${samplePhrase}`,
        xpReward: 4,
        vocabularyId,
      },
      {
        id: `${id}-activity-2`,
        type: "multiple-choice",
        skill: "reading",
        prompt: `What does “${samplePhrase}” mean?`,
        xpReward: 5,
        choices: [
          { id: "correct", text: translation, isCorrect: true },
          { id: "incorrect-1", text: "Good morning", isCorrect: false },
          { id: "incorrect-2", text: "See you later", isCorrect: false },
        ],
      },
      {
        id: `${id}-activity-3`,
        type: "listen-repeat",
        skill: "speaking",
        prompt: `Listen and repeat: ${samplePhrase}`,
        xpReward: 6,
        phraseId,
        speakableText: samplePhrase,
      },
      {
        id: `${id}-activity-4`,
        type: "translate",
        skill: "translation",
        prompt: `Translate: ${translation}`,
        xpReward: 5,
        correctAnswer: samplePhrase,
        acceptedAnswers: [samplePhrase],
      },
    ],
    aiTeacherPrompt: `You are Lingua's friendly language teacher. Teach a beginner the ${title.toLowerCase()} phrase “${samplePhrase}”. Speak slowly, model it twice, and invite the learner to repeat.`,
  };
}

